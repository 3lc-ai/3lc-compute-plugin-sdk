r"""Shared UI component for data-source inputs (files and folders on the compute node).

Generates the HTML + JS block that plugins embed in their UI fragments.
This ensures a consistent file/folder selection experience across every plugin
that needs to reference data on the compute node — local paths, S3 URLs, or
browser-uploaded files all resolve to a compute-visible location.

Usage in a plugin's ``get_ui_fragment()``::

    from tlc_plugin_sdk.shared.data_source_ui import data_source_ui_script
    from tlc_plugin_sdk.shared.ui_inject import inject_scripts

    raw = Path("ui.html").read_text()
    html = inject_scripts(raw, data_source_ui_script())

Then in the plugin's ``ui.html`` JavaScript:

.. code-block:: javascript

    // Render a data-source input
    var html = _tlcDataSourceHtml('my-field', {
        placeholder: 'Path to dataset YAML...',
        accept: '*.yaml,*.yml',      // glob filter for the browser
        allowUpload: false,           // show upload toggle? (never shown for a node run)
    });
    container.innerHTML = html;

    // Bind the browse/upload handlers (call AFTER inserting into DOM)
    _tlcBindDataSource('my-field', computeUrl, pluginId, {
        accept: '*.yaml,*.yml',
        mode: 'file',                 // 'file' or 'folder' ('dir' is read as 'folder')
        purpose: 'input',             // 'input' (default) or 'output': a Save dialog
        suggestedName: 'export.csv',  // output only: what the name box starts with
    });

    // Read the value at submit time
    var path = _tlcGetDataSourceValue('my-field');

The panel is a file chooser. Its path bar: the place being browsed (a machine's folder, a
bucket) is the first crumb and switches places when there are several, the path below it
follows the browsing, and an arrow at its end goes up. Its rows: a click opens a folder, or
picks a file (an output picker puts the file's name in its box instead); the arrow keys
highlight a row, Enter opens a highlighted folder or does the footer's action, Backspace goes
up, Escape closes. Its footer: Cancel and the one action: a file picker's Select (Open for a
highlighted folder), a folder picker's "Select this folder". In a folder picker files are listed
dimmed and cannot be picked. A double-click in the empty field opens the panel, as Browse… does
(the Hub's ``<tlc-table-field>`` does the same for a table URL).

An output picker (``purpose: 'output'``) saves: its footer has a name box, prefilled from
``suggestedName``, and Save (``mode: 'file'``) picks ``<folder shown>/<name>``, adding the first
extension ``accept`` names when the name has none; a click on a file puts its name in the box
and the note says "Replaces <name>". A folder output's box names a new folder under the one
shown (empty: the folder shown itself); an existing name reads "Adds to <name>". ``mode``,
``accept`` and ``suggestedName`` may each be a function, read every time the panel opens.

The widget requires the plugin to serve the ``/browse`` and (optionally)
``/upload-temp`` routes from :mod:`~tlc_plugin_sdk.shared.data_source_routes`.

Browsing is not only the compute's own disk: the place switcher that starts the panel's
path bar lists every bucket the compute service knows (its generic ``/api/infra/storage`` surface, the same
locations as the Hub's Storage page), and browsing one of them goes through the
provider's ``/list`` route **through the Connection the bucket was listed through** —
the listing tags each bucket with its ``connection_id``, and the widget names it on
every later call, as a host with a Config Service requires. Picking a bucket folder
writes its URL (``s3://…``) into the field, which plugins already accept. Volumes are
not offered.

The locations follow the run target, the Hub's "Run on:" choice
(``PLUGIN_API.getRunTarget()``, re-read on ``onRunTargetChange``):

- **Every target.** Explicit ``browse_roots`` offers one location per operator-selected folder,
  labelled by machine and folder. Empty roots offer buckets only; a compute host with empty roots
  and no bucket says its operator offers folders with ``TLC_DATA_SOURCE_ROOTS``. Node folders are
  browsed through the host; Upload is unavailable for node targets. Older bridges without root
  metadata retain their previous disk-location behavior.

A value the run target cannot reach — a folder picked on this computer and then a node chosen, a
typed path the node does not have, a bucket the node's probe says it cannot read — gets a note
under the field naming why and what the run will do. On a Hub without ``getRunTarget`` the widget
behaves as before run targets: the compute's disk only when it is this computer, then the buckets.
Without an infrastructure plugin (or on a host without that surface) the bar shows only
"This computer" on older hosts; explicit empty roots offer no disk.
"""

